/**
 * AJAX Login Block Class
 *
 * Registers and renders the login block for Gutenberg.
 *
 * @package    Recaptcha_For_BuddyPress
 * @subpackage bp_recaptcha/includes
 * @author     Wbcom Designs <admin@wbcomdesigns.com>
 */
class WBC_Login_Block {

	/**
	 * Register the block
	 */
	public function register_block() {
		// Register the block using block.json.
		register_block_type_from_metadata(
			plugin_dir_path( __DIR__ ) . 'blocks/login-widget',
			array(
				'render_callback' => array( $this, 'render_block' ),
			)
		);

		/*
		 * Load the editor script's JED translations from the plugin's own
		 * languages/ directory.
		 *
		 * block.json already declares "textdomain", which makes core call
		 * wp_set_script_translations() for us -- but core calls it WITHOUT a
		 * path, so WP only looks in WP_LANG_DIR/plugins/. This plugin is
		 * self-hosted (wbcomdesigns.com), not WP.org, so its .json JED files
		 * ship inside the plugin instead. Without the explicit path below,
		 * every wp.i18n.__() call in blocks/login-widget/index.js renders
		 * English on a fully translated site.
		 *
		 * Handle name is generated by core from the block name:
		 * 'wbc/login-widget' + editorScript -> 'wbc-login-widget-editor-script'.
		 */
		wp_set_script_translations(
			'wbc-login-widget-editor-script',
			'buddypress-recaptcha',
			RFB_PLUGIN_PATH . 'languages'
		);
	}

	/**
	 * Render the block
	 *
	 * @param array $attributes Block attributes.
	 * @return string Block HTML.
	 */
	public function render_block( $attributes ) {
		wp_enqueue_style( 'wbc-ajax-login' );
		wp_enqueue_script( 'wbc-ajax-login' );

		// Convert attributes to widget instance format.
		$instance = array(
			'welcome_message'    => ! empty( $attributes['welcomeMessage'] ) ? $attributes['welcomeMessage'] : __( 'Welcome back, {username}!', 'buddypress-recaptcha' ),
			'redirect_url'       => ! empty( $attributes['redirectUrl'] ) ? $attributes['redirectUrl'] : home_url(),
			'show_lost_password' => isset( $attributes['showLostPassword'] ) && $attributes['showLostPassword'] ? 'yes' : 'no',
			'show_register_link' => isset( $attributes['showRegisterLink'] ) && $attributes['showRegisterLink'] ? 'yes' : 'no',
			'show_profile_link'  => isset( $attributes['showProfileLink'] ) && $attributes['showProfileLink'] ? 'yes' : 'no',
		);

		// Start output buffering.
		ob_start();

		echo '<div class="wp-block-wbc-login-widget">';

		if ( is_user_logged_in() ) {
			WBC_Login_Widget::render_logged_in_view( $instance );
		} else {
			WBC_Login_Widget::render_login_form( $instance );
		}

		echo '</div>';

		return ob_get_clean();
	}
}
